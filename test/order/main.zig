//! Writes the linker script that puts the functions `lua` runs first at
//! the front of its code, so the pages a short run touches are few and
//! together: `just order`. The kernel maps an executable's code 64 KiB
//! around each page that faults, so a run that touches one function in
//! each 64 KiB keeps nearly all the code resident
//! (docs/slop/results/lean-20261031.md).
//!
//! `order OUT -- BIN ARGS... [-- BIN ARGS...]...` runs each command under
//! ptrace, in the tool's environment, with a breakpoint on the entry of
//! every function in BIN's symbol table, records the functions in the
//! order they are first called, and writes them to OUT as input section
//! patterns for LLD, in that order across the runs. The executable links
//! with `-ffunction-sections`, so each function is a section `.text.NAME`
//! (`.text.unlikely.NAME` for a cold one). Generic instance numbers are
//! wildcards, so the script survives edits that renumber them; where
//! instances share a pattern, a cold one is listed by its exact name, so
//! an uncalled cold instance, the hooked interpreter loop, stays out.
//! In a C-API build, glibc's `_start` comes from crt1.o, whose code is
//! plain `.text`, and the PLT, which startup calls, moves up too.

const std = @import("std");
const linux = std.os.linux;
const elf = std.elf;

const Func = struct { addr: u64, name: []const u8, saved: u8 = 0 };

pub fn main(init: std.process.Init) !void {
    const gpa = init.gpa;
    const io = init.io;
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len < 4 or !std.mem.eql(u8, args[2], "--")) return error.Usage;
    // The patterns of the functions called, in order of first call, and
    // the exact names each stands for.
    var order: std.ArrayList([]const u8) = .empty;
    var seen: std.StringArrayHashMapUnmanaged(std.ArrayList([]const u8)) = .empty;
    // Patterns that match more than one function in some binary.
    var shared: std.StringHashMapUnmanaged(void) = .empty;
    var i: usize = 3;
    while (i < args.len) {
        var j = i;
        while (j < args.len and !std.mem.eql(u8, args[j], "--")) j += 1;
        var count: std.StringHashMapUnmanaged(void) = .empty;
        for ((try readFuncs(gpa, io, args[i])).items) |f| {
            const p = try pattern(gpa, f.name, true);
            if ((try count.getOrPut(gpa, p)).found_existing) try shared.put(gpa, p, {});
        }
        for (try trace(gpa, io, args[i..j], init.minimal.environ.block.slice.ptr)) |n| {
            const gop = try seen.getOrPut(gpa, try pattern(gpa, n, true));
            if (!gop.found_existing) {
                gop.value_ptr.* = .empty;
                try order.append(gpa, gop.key_ptr.*);
            }
            const exact = try pattern(gpa, n, false);
            for (gop.value_ptr.items) |e| {
                if (std.mem.eql(u8, e, exact)) break;
            } else try gop.value_ptr.append(gpa, exact);
        }
        i = j + 1;
    }
    var buf: [4096]u8 = undefined;
    const file = try std.Io.Dir.cwd().createFile(io, args[1], .{});
    defer file.close(io);
    var fw = file.writer(io, &buf);
    const w = &fw.interface;
    try w.writeAll(
        \\/* Generated by `just order` from test/order: the functions lua calls
        \\   first, in that order, ahead of the rest of its code. Regenerate it
        \\   when startup changes; a stale line costs memory, not correctness. */
        \\SECTIONS {
        \\  .plt : { *(.plt) }
        \\  .text.hot : {
        \\    *crt1.o(.text .text.*)
        \\
    );
    for (order.items) |p| {
        try w.print("    *(.text.{s}", .{p});
        if (!shared.contains(p)) {
            try w.print(" .text.unlikely.{s}", .{p});
        } else for (seen.get(p).?.items) |n| try w.print(" .text.unlikely.{s}", .{n});
        // compiler_rt's functions keep its namespace in their sections.
        if (std.mem.findScalar(u8, p, '.') == null) try w.print(" .text.compiler_rt.{s}", .{p});
        try w.writeAll(")\n");
    }
    try w.writeAll("  }\n} INSERT BEFORE .text;\n");
    try w.flush();
}

/// `name` as a glob: generic instance numbers become `*` if `wild`, and
/// characters a linker script would split a pattern on become `?`.
fn pattern(gpa: std.mem.Allocator, name: []const u8, wild: bool) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    var k: usize = 0;
    while (k < name.len) {
        for ([_][]const u8{ "__anon_", "__struct_" }) |tag| {
            if (wild and std.mem.startsWith(u8, name[k..], tag)) {
                try out.appendSlice(gpa, tag);
                try out.append(gpa, '*');
                k += tag.len;
                while (k < name.len and std.ascii.isDigit(name[k])) k += 1;
                break;
            }
        } else {
            const c = name[k];
            try out.append(gpa, if (std.ascii.isAlphanumeric(c) or c == '_' or c == '.') c else '?');
            k += 1;
        }
    }
    return out.items;
}

/// Runs `argv` with a breakpoint at every function's entry and returns
/// the functions' names in the order of their first calls.
fn trace(gpa: std.mem.Allocator, io: std.Io, argv: []const [:0]const u8, envp: [*:null]const ?[*:0]const u8) ![]const []const u8 {
    var funcs = try readFuncs(gpa, io, argv[0]);
    const pid = try spawnTraced(gpa, argv, envp);
    var status: u32 = 0;
    _ = linux.waitpid(pid, &status, 0); // stopped at the exec
    for (funcs.items) |*f| {
        const word = try peek(pid, f.addr);
        f.saved = @truncate(word);
        try poke(pid, f.addr, (word & ~@as(u64, 0xff)) | 0xcc);
    }
    var names: std.ArrayList([]const u8) = .empty;
    var sig: usize = 0;
    while (true) {
        _ = linux.ptrace(linux.PTRACE.CONT, pid, 0, sig, 0);
        _ = linux.waitpid(pid, &status, 0);
        if (linux.W.IFEXITED(status) or linux.W.IFSIGNALED(status)) break;
        sig = @intFromEnum(linux.W.STOPSIG(status));
        if (sig != @intFromEnum(linux.SIG.TRAP)) continue;
        sig = 0;
        // rip is word 16 of `user_regs_struct`; it is one past the int3.
        const rip = try peekUser(pid, 16 * 8);
        const at = std.sort.binarySearch(Func, funcs.items, rip - 1, findAddr) orelse continue;
        const f = &funcs.items[at];
        try poke(pid, f.addr, (try peek(pid, f.addr) & ~@as(u64, 0xff)) | f.saved);
        _ = linux.ptrace(linux.PTRACE.POKEUSER, pid, 16 * 8, f.addr, 0);
        try names.append(gpa, f.name);
    }
    return names.items;
}

fn findAddr(addr: u64, f: Func) std.math.Order {
    return std.math.order(addr, f.addr);
}

fn spawnTraced(gpa: std.mem.Allocator, argv: []const [:0]const u8, envp: [*:null]const ?[*:0]const u8) !linux.pid_t {
    const cargv = try gpa.allocSentinel(?[*:0]const u8, argv.len, null);
    for (argv, 0..) |a, k| cargv[k] = a.ptr;
    const r = linux.fork();
    if (linux.errno(r) != .SUCCESS) return error.Fork;
    if (r == 0) {
        _ = linux.ptrace(linux.PTRACE.TRACEME, 0, 0, 0, 0);
        _ = linux.execve(argv[0].ptr, cargv.ptr, envp);
        linux.exit(127);
    }
    return @intCast(r);
}

fn peek(pid: linux.pid_t, addr: u64) !u64 {
    var word: u64 = 0;
    if (linux.errno(linux.ptrace(linux.PTRACE.PEEKTEXT, pid, addr, @intFromPtr(&word), 0)) != .SUCCESS)
        return error.Peek;
    return word;
}

fn peekUser(pid: linux.pid_t, off: u64) !u64 {
    var word: u64 = 0;
    if (linux.errno(linux.ptrace(linux.PTRACE.PEEKUSER, pid, off, @intFromPtr(&word), 0)) != .SUCCESS)
        return error.Peek;
    return word;
}

fn poke(pid: linux.pid_t, addr: u64, word: u64) !void {
    if (linux.errno(linux.ptrace(linux.PTRACE.POKETEXT, pid, addr, word, 0)) != .SUCCESS) return error.Poke;
}

/// The defined functions of the executable at `path`, by address.
fn readFuncs(gpa: std.mem.Allocator, io: std.Io, path: []const u8) !std.ArrayList(Func) {
    const data = try std.Io.Dir.cwd().readFileAlloc(io, path, gpa, .limited(1 << 30));
    const eh: *align(1) const elf.Elf64_Ehdr = @ptrCast(data.ptr);
    const shdrs: []align(1) const elf.Elf64_Shdr = @as([*]align(1) const elf.Elf64_Shdr, @ptrCast(data.ptr + eh.e_shoff))[0..eh.e_shnum];
    var funcs: std.ArrayList(Func) = .empty;
    for (shdrs) |sh| {
        if (sh.sh_type != elf.SHT_SYMTAB) continue;
        const strtab = shdrs[sh.sh_link];
        const n = sh.sh_size / @sizeOf(elf.Elf64_Sym);
        const syms: []align(1) const elf.Elf64_Sym = @as([*]align(1) const elf.Elf64_Sym, @ptrCast(data.ptr + sh.sh_offset))[0..n];
        for (syms) |s| {
            if (s.st_info & 0xf != elf.STT_FUNC or s.st_size == 0 or s.st_value == 0) continue;
            const name = std.mem.sliceTo(data[strtab.sh_offset + s.st_name ..], 0);
            try funcs.append(gpa, .{ .addr = s.st_value, .name = name });
        }
    }
    std.mem.sort(Func, funcs.items, {}, struct {
        fn lt(_: void, a: Func, b: Func) bool {
            return a.addr < b.addr;
        }
    }.lt);
    // Aliases share an address; one breakpoint each.
    var out: usize = 0;
    for (funcs.items) |f| {
        if (out > 0 and funcs.items[out - 1].addr == f.addr) continue;
        funcs.items[out] = f;
        out += 1;
    }
    funcs.items.len = out;
    return funcs;
}
